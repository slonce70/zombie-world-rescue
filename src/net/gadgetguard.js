// 🛡️ Ліміти каналу гаджетів: хост вирішує, чи пускати повідомлення гостя.
// Чиста логіка — без THREE, DOM і мережі, тож її ганяє звичайний node-юніт
// (прецедент: stars.js / tier2.js / combatmomentum.js).
//
// Чотири шари, усі на боці ХОСТА:
//   1. Право   — карткові ефекти пускаємо за ПІДТВЕРДЖЕНИМ вибором гостя (`dpk`, PROTO 26)
//                або за спільною збіркою забігу; посилення гаджета — за оголошеним
//                гіперзарядом, звіреним із каталогом магазину.
//   2. Частота — свій мінімальний інтервал на кожен тип, із запасом до легального темпу.
//   3. Стеля   — скільки обʼєктів одного типу гість тримає живими одночасно.
//   4. Стеля КІМНАТИ — скільки їх у світі всього. Вона не залежить від номера гравця,
//                тож цикл «вийшов — зайшов із новим pid» її не скидає.
//
// Відмова ТИХА: повідомлення просто зникає. Кімнату не рвемо і гостю нічого не
// повідомляємо — у дитячому коопі лаг звичайніший за чит, а модифікований клієнт
// не має дізнаватись, де саме проходить межа.

// Таблиця лімітів. Тип БЕЗ рядка тут не пройде `checkGadget` взагалі — саме тому
// новий гаджет неможливо додати повз перевірку.
//
// Частота (`minGapMs` + `burst`). Легальний темп гаджетів задає ОДИН спільний
// кулдаун (`extras.js`, `GADGETS[id].cd`: батут 20с, барикада 25с, турель і метеорит
// 45с) — після будь-якого гаджета мовчать усі, тож інтервал між двома установками
// ОДНОГО типу у чесного гостя ніколи не менший за його власний кулдаун. Беремо ~40%
// кулдауна: мережа може лише ЗАТРИМАТИ пакет, тож дрижання здатне тільки зблизити
// сусідні повідомлення — двократний запас це перекриває з головою.
// Вогняний слід — не гаджет, а картка драфту: падає раз на 0.5с бігу і раз на
// 0.3с у спринті (`player.js`, FIRE_TRAIL_STEP/FIRE_TRAIL_SPRINT), тож 150 мс — той
// самий двократний запас.
// `burst` — скільки повідомлень поспіль пускаємо, поки бюджет накопичений (відро
// жетонів: жетон повертається раз на `minGapMs`). Це запас саме під ХОСТА: коли
// його кадр підвисає, кілька чесних повідомлень чекають у сокеті й обробляються
// одним тиком, тобто з нульовим інтервалом. Швидкому сліду даємо 4 жетони;
// гаджетам вистачає одного — їхні чесні інтервали в десятки секунд.
//
// Стеля. `lifeMs: 0` означає «живих рахує сам світ за власником обʼєкта»
// (стіни/батути/турелі мають `ownerPid`); інакше guard рахує сам — за часом життя
// обʼєкта, бо у метеорита й сліду власника у світі немає.
//
// Стеля КІМНАТИ (`roomMax`) рахує ті самі обʼєкти, але БЕЗ огляду на власника —
// саме тому перепідключення з новим номером гравця її не обходить. Числа взяті так,
// щоб чесна кімната на чотирьох у них не впиралась: персональна стеля × 3 гості
// плюс запас на господаря (детальний розрахунок — у тікеті 05).
//
// `hyper: true` — у типу є куплена посилена версія (гіперзаряд із магазину). Прапорець
// у повідомленні сам собою нічого не значить: посилення вмикається, лише якщо цей
// гіперзаряд є у списку, який гість оголосив при вході (санітизованому каталогом).
export const GADGET_LIMITS = {
  // 🧱 барикада: у світі стелі немає взагалі, тож саме тут стеля має сенс.
  // 16 живих стін = понад 4 хвилини установок у максимальному ЧЕСНОМУ темпі,
  // і це ще й стеля витрат хоста (кожна стіна — 3 колайдери + перебудова сітки).
  wall: { minGapMs: 10000, maxActive: 16, roomMax: 48, lifeMs: 0 },
  // 🦘 батут: світ і так тримає лише 3 найновіші НА ВСІХ (`_buildTramp` викидає
  // найстаріший), тож 4 — страховка, яка не заважає чесній заміні свого ж батута.
  tramp: { minGapMs: 8000, maxActive: 4, roomMax: 8, lifeMs: 0 },
  // 🤖 турель: світ тримає ОДНУ на власника — нова замінює стару (`_buildTurret`).
  // Тому стеля 2, а не 1: інакше чесна заміна впиралась би у власну ж турель.
  turret: { minGapMs: 18000, maxActive: 2, roomMax: 8, lifeMs: 0, hyper: true },
  // ☄️ метеорит: власника у світі немає — рахуємо самі за часом життя вогнища
  // гіпер-метеорита (10с) із запасом. Інтервал 18с і так пускає щонайбільше два.
  meteor: { minGapMs: 18000, maxActive: 2, roomMax: 8, lifeMs: 20000, hyper: true },
  // 🌋 вогняний слід: картка драфту, живе 2.4с (FIRE_TRAIL_LIFE). Чесний максимум —
  // 2.4/0.3 = 8 плям одночасно, стеля 12 лишає півтора запасу. Саме стеля тут і
  // тримає межу: вона не залежить від того, як рівно приїхали пакети.
  firetrail: { minGapMs: 150, burst: 4, maxActive: 12, roomMax: 40, lifeMs: 2400, card: 'firetrail' },
};

export const GADGET_KINDS = Object.keys(GADGET_LIMITS);

// Скільки невибраних наборів драфту тримаємо на гостя. Оверлей у гостя один і
// новий набір поверх старого не відкривається, тож черга потрібна лише на випадок
// «хвиля пішла, поки гість думає». Понад це — найстаріший набір забуваємо.
const MAX_PENDING_OFFERS = 4;

// Стан лімітів ОДНОГО гостя. Живе на його `RemotePlayer`: гість відвалився —
// стан пішов разом з ним (витоку немає), перепідключився — почав з чистого.
// Саме тому персональних шарів МАЛО: понад ними стоїть стеля кімнати, яка від
// номера гравця не залежить (той самий createGadgetGuard, один на кімнату).
export function createGadgetGuard() {
  return {
    last: Object.create(null),   // коли тип пройшов востаннє
    tokens: Object.create(null), // скільки жетонів частоти лишилось
    live: Object.create(null),   // час народження обʼєктів, які guard рахує сам
    pending: [],                 // набори драфту, з яких гість ще не обрав (Set-и id)
    picked: Object.create(null), // що гість ПІДТВЕРДЖЕНО взяв і скільки разів
  };
}

// 🎲 Хост роздав гостю набір драфту (подія `dro`) — запамʼятовуємо, З ЧОГО гість
// обиратиме. Саме по собі це права ще не дає: набір — пропозиція, а не вибір.
export function offerDraftCards(guard, ids) {
  if (!guard || !Array.isArray(ids)) return guard;
  const clean = ids.filter((id) => typeof id === 'string' && id);
  if (!clean.length) return guard; // сміття замість набору не пропонує нічого
  guard.pending.push(new Set(clean));
  while (guard.pending.length > MAX_PENDING_OFFERS) guard.pending.shift();
  return guard;
}

// 🎲 Гість повідомив, ЩО взяв (`dpk`, PROTO 26) — ПЕРШЕ джерело права на карткові
// ефекти. Хост звіряє вибір із набором, який сам надіслав: картку зараховуємо, а
// сам набір «витрачаємо». Тому повторне повідомлення про той самий вибір права не
// додає, а вибір, якого в жодному невитраченому наборі не було, відхиляється.
export function takeDraftCard(guard, id) {
  if (!guard || typeof id !== 'string' || !id) return false;
  const i = guard.pending.findIndex((offer) => offer.has(id));
  if (i < 0) return false;
  guard.pending.splice(i, 1);
  guard.picked[id] = (guard.picked[id] || 0) + 1;
  return true;
}

// 🎒 ДРУГЕ джерело права: СПІЛЬНА збірка забігу, яку хост роздав усій кімнаті
// (Експедиція і Фронт — там збірка приїжджає гостю у spec і застосовується обом).
// На відміну від набору драфту це дані АВТОРИТЕТНІ: хост знає не «що показав», а
// «що в гостя є». Тому рахуємо входження — саме тут і лише тут посилена версія
// картки може бути законною.
function countInBuild(build, id) {
  if (!Array.isArray(build)) return 0;
  let n = 0;
  for (const item of build) if (item === id) n++;
  return n;
}

// скільки обʼєктів типу ще живі за власним обліком guard-а (і заразом прибирає протухлі)
function liveByTime(guard, kind, now, lifeMs) {
  const log = guard.live[kind] || (guard.live[kind] = []);
  let gone = 0;
  while (gone < log.length && now - log[gone] >= lifeMs) gone++;
  if (gone) log.splice(0, gone);
  return log.length;
}

const deny = (reason) => ({ ok: false, strong: false, reason });

// Рішення «пускати / не пускати» для одного повідомлення гостя.
// `opts.strong` — прапорець `hyper` з повідомлення (сам собою НЕ довіра),
// `opts.hypers` — гіперзаряди, які гість оголосив при вході (санітизовані каталогом),
// `opts.build`  — спільна збірка забігу, яку хост роздав кімнаті (або null),
// `opts.active` — скільки обʼєктів цього типу гість тримає живими у світі,
// `opts.room`   — стан кімнати (той самий createGadgetGuard, один на всіх),
// `opts.roomActive` — скільки обʼєктів цього типу у світі ВСЬОГО, без огляду на власника.
// Повертає { ok, strong, reason }: `strong` уже санітизований — хост має брати
// саме його, а не сире поле повідомлення.
export function checkGadget(guard, kind, now, opts = {}) {
  const lim = GADGET_LIMITS[kind];
  if (!lim) return deny('unknown');
  if (!guard || !Number.isFinite(now)) return deny('state');

  // 🚫 Посилена версія за замовчуванням — НІ: `hyper` у повідомленні це слово гостя.
  // Вмикається лише там, де в хоста є з чим його звірити (оголошений гіперзаряд,
  // підтверджений вибір картки, спільна збірка).
  let strong = false;
  if (lim.card) {
    // Право на КАРТКОВИЙ ефект. Два джерела, обидва — «що хост сам дав цьому гостю»:
    //   (а) підтверджений вибір із набору, який хост же й надіслав (`takeDraftCard`);
    //   (б) спільна збірка забігу кімнати (Експедиція, Фронт).
    // Немає ні там, ні там — картки в гостя не було звідки взяти (кооп-кампанія:
    // збірки забігу гостю взагалі не створюють).
    const got = (guard.picked[lim.card] || 0) + countInBuild(opts.build, lim.card);
    if (got < 1) return deny('nocard');
    // Посилення картки = «взяв її двічі», і обидва джерела це рахують чесно.
    strong = !!opts.strong && got >= 2;
  } else if (lim.hyper) {
    // Право на ПОСИЛЕНИЙ гаджет — куплений гіперзаряд, який гість оголосив при вході.
    // Це самооголошення (див. `sanitizeHypers` у coop.js): мета — повернути чесному
    // гравцю куплене за 5000 монет, коли він грає гостем, а не збудувати античит.
    strong = !!opts.strong && Array.isArray(opts.hypers) && opts.hypers.includes(kind);
  }

  // Частота: відро жетонів. Один жетон повертається раз на `minGapMs`, більше за
  // `burst` не накопичується. При burst = 1 це звичайний мінімальний інтервал.
  const full = lim.burst || 1;
  const last = guard.last[kind];
  const tokens = last === undefined ? full
    : Math.min(full, (guard.tokens[kind] || 0) + Math.max(0, now - last) / lim.minGapMs);
  if (tokens < 1) return deny('rate');

  // Стеля персональна…
  const live = lim.lifeMs
    ? liveByTime(guard, kind, now, lim.lifeMs)
    : Math.max(0, Math.floor(Number(opts.active) || 0));
  if (live >= lim.maxActive) return deny('cap');

  // …і стеля КІМНАТИ поверх неї. Вона рахує обʼєкти без огляду на власника, тож
  // цикл «вийшов — зайшов із новим номером» її не скидає. Обʼєкти того, хто пішов,
  // лишаються у світі (обрив на секунду не має зносити чужі барикади) — і рахуються.
  const room = opts.room;
  if (lim.roomMax) {
    const roomLive = lim.lifeMs
      ? (room ? liveByTime(room, kind, now, lim.lifeMs) : 0)
      : Math.max(0, Math.floor(Number(opts.roomActive) || 0));
    if (roomLive >= lim.roomMax) return deny('room');
  }

  guard.last[kind] = now;
  guard.tokens[kind] = tokens - 1;
  if (lim.lifeMs) {
    guard.live[kind].push(now);
    if (room && lim.roomMax) room.live[kind].push(now);
  }
  return { ok: true, strong, reason: null };
}
